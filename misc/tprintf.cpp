int __not_in_flash_func(tputchar)(int x, int y, int ch) {
    const uint8_t *f = font5x8 + (ch << 3);
    uint16_t *d = &fb[fbIdx][y*X_RES + x];

    for (int y = 0; y < 8; y++) {
        int gl = *f++;
        
        if (gl & (0x80)) d[0] = 0x7FFF;
        if (gl & (0x40)) d[1] = 0x7FFF;
        if (gl & (0x20)) d[2] = 0x7FFF;
        if (gl & (0x10)) d[3] = 0x7FFF;
        if (gl & (0x08)) d[4] = 0x7FFF;

        d += X_RES;
    }
    return 0;
}

int __not_in_flash_func(tputstr)(int x, int y, const char *str) {
    while (*str != 0) {
        tputchar(x, y, *str++); x += 5;
    }
    return 0;
}

