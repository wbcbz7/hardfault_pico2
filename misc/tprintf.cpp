int __not_in_flash_func(tprintf)(int x, int y, const char *format, ...) {
    char buffer[128];      // large enough
    va_list arglist;

    va_start(arglist, format);
    int rtn = vsnprintf(buffer, sizeof(buffer), format, arglist);
    tputstr(x, y, buffer);
    va_end(arglist);

    return rtn;
};

